//! Talend jobs to a dbt project for the lakehouse (EKOS RFC 0268, phase 1). Pure: a project, the
//! lakehouse plan and settings in; files and a report out.
//!
//! Each latest job is lowered by `talend-rel` (RFC 0267). The row-local chain from each source is
//! a silver model; everything upstream of a sink, stopping at silver models, is a gold model,
//! materialized by the sink's data action (the rules in [`Rule`]). A table one job writes is a
//! `ref()` in every job that reads it. A model with a gap in its nodes, or one that fails a gate,
//! is written disabled with its reasons.

