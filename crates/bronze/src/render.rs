//! RFC 0192 §4–5: the SQL files a plan generates. Deterministic: the same plan renders the same
//! bytes. Placeholders the orchestrator fills at run time: `{{run_id}}`, `{{lsn}}` (both
//! SQL-escaped by the caller) and `{{watermark}}` (a typed literal, or `NULL` on the first run).

use crate::mode::LoadMode;
use crate::plan::{Plan, PlanSettings, TablePlan};
use crate::typemap::ident;
use std::collections::BTreeMap;

const HEADER: &str = "-- Generated by ekos-lakehouse (RFC 0192). Do not edit: regenerate.\n";

/// Bronze's own columns, after the source's.
pub const META_COLUMNS: &[(&str, &str)] = &[
    ("_ekos_loaded_at", "timestamp(6) with time zone"),
    ("_ekos_run_id", "varchar"),
    ("_ekos_source_lsn", "varchar"),
    ("_ekos_op", "varchar"),
];

pub fn target(t: &TablePlan, s: &PlanSettings) -> String {
    format!(
        "{}.{}.{}",
        ident(&s.target_catalog),
        ident(&t.namespace),
        ident(&t.table)
    )
}

pub fn source(t: &TablePlan, s: &PlanSettings) -> String {
    format!(
        "{}.{}.{}",
        ident(&s.source_catalog),
        ident(&t.schema),
        ident(&t.table)
    )
}

fn select_list(t: &TablePlan, op: &str) -> String {
    let mut cols: Vec<String> = t
        .columns
        .iter()
        .map(|m| {
            if m.expr == ident(&m.column) {
                m.expr.clone()
            } else {
                format!("{} AS {}", m.expr, ident(&m.column))
            }
        })
        .collect();
    cols.push(
        "CAST(current_timestamp AS timestamp(6) with time zone) AS \"_ekos_loaded_at\"".into(),
    );
    cols.push("CAST('{{run_id}}' AS varchar) AS \"_ekos_run_id\"".into());
    cols.push("CAST('{{lsn}}' AS varchar) AS \"_ekos_source_lsn\"".into());
    cols.push(format!("CAST('{op}' AS varchar) AS \"_ekos_op\""));
    cols.join(",\n  ")
}

pub fn namespace_sql(namespace: &str, s: &PlanSettings) -> String {
    format!(
        "{HEADER}CREATE SCHEMA IF NOT EXISTS {}.{}\n",
        ident(&s.target_catalog),
        ident(namespace)
    )
}

/// The load statement. Full: replace the table in one commit. Incremental: create it once, then
/// append rows at or after the watermark.
pub fn load_sql(t: &TablePlan, s: &PlanSettings) -> String {
    let (tgt, src) = (target(t, s), source(t, s));
    match &t.decision.mode {
        LoadMode::Full => format!(
            "{HEADER}CREATE OR REPLACE TABLE {tgt}\nWITH (format = 'PARQUET')\nAS SELECT\n  {}\nFROM {src}\n",
            select_list(t, "load")
        ),
        LoadMode::Incremental { watermark, .. } => {
            let w = ident(watermark);
            format!(
                "{HEADER}INSERT INTO {tgt}\nSELECT\n  {}\nFROM {src}\nWHERE {{{{watermark}}}} IS NULL OR {w} >= {{{{watermark}}}}\n",
                select_list(t, "upsert")
            )
        }
    }
}

/// For an incremental table: create it, empty, with bronze's columns. Run before the first load.
pub fn create_sql(t: &TablePlan, s: &PlanSettings) -> Option<String> {
    matches!(t.decision.mode, LoadMode::Incremental { .. }).then(|| {
        format!(
            "{HEADER}CREATE TABLE IF NOT EXISTS {}\nWITH (format = 'PARQUET')\nAS SELECT\n  {}\nFROM {}\nWITH NO DATA\n",
            target(t, s),
            select_list(t, "upsert"),
            source(t, s)
        )
    })
}

/// The highest watermark already loaded, as text; the orchestrator turns it into a literal.
pub fn watermark_sql(t: &TablePlan, s: &PlanSettings) -> Option<String> {
    match &t.decision.mode {
        LoadMode::Incremental { watermark, .. } => Some(format!(
            "{HEADER}SELECT CAST(max({}) AS varchar) FROM {} WHERE \"_ekos_op\" <> 'delete'\n",
            ident(watermark),
            target(t, s)
        )),
        LoadMode::Full => None,
    }
}

/// Bronze's current state: the latest version of each key, tombstones removed. For a full table,
/// the table itself.
pub fn current_sql(t: &TablePlan, s: &PlanSettings) -> String {
    let cols: Vec<String> = t.columns.iter().map(|m| ident(&m.column)).collect();
    let cols = cols.join(", ");
    match &t.decision.mode {
        LoadMode::Full => format!("SELECT {cols} FROM {}", target(t, s)),
        LoadMode::Incremental { .. } => {
            let key: Vec<String> = t.primary_key.iter().map(|k| ident(k)).collect();
            format!(
                "SELECT {cols} FROM (SELECT *, row_number() OVER (PARTITION BY {} \
                 ORDER BY \"_ekos_loaded_at\" DESC) AS \"_ekos_rn\" FROM {}) \
                 WHERE \"_ekos_rn\" = 1 AND \"_ekos_op\" <> 'delete'",
                key.join(", "),
                target(t, s)
            )
        }
    }
}

/// For an incremental table with a key: a tombstone for every current key the source lacks.
pub fn deletes_sql(t: &TablePlan, s: &PlanSettings) -> Option<String> {
    let LoadMode::Incremental {
        keyset_deletes: true,
        ..
    } = &t.decision.mode
    else {
        return None;
    };
    let key: Vec<String> = t.primary_key.iter().map(|k| ident(k)).collect();
    let by_name = |k: &str| t.columns.iter().find(|m| m.column == k);
    let src_key: Vec<String> = t
        .primary_key
        .iter()
        .map(|k| {
            let expr = by_name(k).map_or_else(|| ident(k), |m| m.expr.clone());
            format!("{expr} AS {}", ident(k))
        })
        .collect();
    let columns: Vec<String> = t
        .columns
        .iter()
        .map(|m| {
            if t.primary_key.contains(&m.column) {
                format!("b.{}", ident(&m.column))
            } else {
                format!("CAST(NULL AS {}) AS {}", m.iceberg_type, ident(&m.column))
            }
        })
        .collect();
    let join: Vec<String> = key.iter().map(|k| format!("s.{k} = b.{k}")).collect();
    Some(format!(
        "{HEADER}INSERT INTO {tgt}\nSELECT\n  {cols},\n  CAST(current_timestamp AS timestamp(6) with time zone),\n  \
         CAST('{{{{run_id}}}}' AS varchar),\n  CAST('{{{{lsn}}}}' AS varchar),\n  CAST('delete' AS varchar)\n\
         FROM ({current}) AS b\nLEFT JOIN (SELECT {src_key} FROM {src}) AS s ON {join}\nWHERE s.{first} IS NULL\n",
        tgt = target(t, s),
        cols = columns.join(",\n  "),
        current = current_sql(t, s),
        src_key = src_key.join(", "),
        src = source(t, s),
        join = join.join(" AND "),
        first = key[0],
    ))
}

/// Iceberg maintenance (RFC 0192 §4): compaction, snapshot expiry, orphan removal.
pub fn maintenance_sql(t: &TablePlan, s: &PlanSettings) -> String {
    let tgt = target(t, s);
    format!(
        "{HEADER}ALTER TABLE {tgt} EXECUTE optimize;\n\
         ALTER TABLE {tgt} EXECUTE expire_snapshots(retention_threshold => '7d');\n\
         ALTER TABLE {tgt} EXECUTE remove_orphan_files(retention_threshold => '7d');\n"
    )
}

/// Every file of the plan, by its path in the pipeline repository.
pub fn files(plan: &Plan) -> BTreeMap<String, String> {
    let s = &plan.settings;
    let mut out = BTreeMap::new();
    out.insert(
        "lakehouse.lock.json".to_string(),
        serde_json::to_string_pretty(plan).expect("a plan serializes") + "\n",
    );
    for t in &plan.tables {
        let dir = format!("bronze/{}/{}", t.schema, t.table);
        out.entry(format!("bronze/{}/_namespace.sql", t.schema))
            .or_insert_with(|| namespace_sql(&t.namespace, s));
        out.insert(format!("{dir}/load.sql"), load_sql(t, s));
        out.insert(format!("{dir}/maintenance.sql"), maintenance_sql(t, s));
        out.insert(
            format!("{dir}/current.sql"),
            format!("{HEADER}{}\n", current_sql(t, s)),
        );
        if let Some(sql) = create_sql(t, s) {
            out.insert(format!("{dir}/create.sql"), sql);
        }
        if let Some(sql) = watermark_sql(t, s) {
            out.insert(format!("{dir}/watermark.sql"), sql);
        }
        if let Some(sql) = deletes_sql(t, s) {
            out.insert(format!("{dir}/deletes.sql"), sql);
        }
    }
    out
}

/// Fill a template's run-time placeholders (what the orchestrator does before running a file).
/// `run_id` and `lsn` are quoted as SQL string content here; `watermark` is a ready SQL literal
/// from [`watermark_literal`].
pub fn fill(template: &str, run_id: &str, lsn: &str, watermark: &str) -> String {
    let q = |s: &str| s.replace('\'', "''");
    template
        .replace("{{run_id}}", &q(run_id))
        .replace("{{lsn}}", &q(lsn))
        .replace("{{watermark}}", watermark)
}

/// The watermark as a typed SQL literal: `NULL` before the first load, else
/// `CAST('<text>' AS <type>)` with the column's bronze type.
pub fn watermark_literal(text: Option<&str>, iceberg_type: &str) -> String {
    match text {
        None | Some("") => "NULL".into(),
        Some(v) => format!("CAST('{}' AS {iceberg_type})", v.replace('\'', "''")),
    }
}

/// The statements of a generated file, without the header and trailing `;` (Trino runs one
/// statement per request).
pub fn statements(file: &str) -> Vec<String> {
    file.split(";\n")
        .map(|s| {
            s.lines()
                .filter(|l| !l.starts_with("--"))
                .collect::<Vec<_>>()
                .join("\n")
                .trim()
                .trim_end_matches(';')
                .to_string()
        })
        .filter(|s| !s.is_empty())
        .collect()
}
