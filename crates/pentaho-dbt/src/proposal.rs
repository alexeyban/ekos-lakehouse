//! The reviewer's view of a translation: `proposals/pentaho-<package>.md`.

use crate::{Layer, Report};
use ekos_lakehouse_kettle_expr::Fidelity;

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn fence(text: &str, lang: &str, max_lines: usize) -> String {
    let lines: Vec<&str> = text.lines().collect();
    let shown = lines
        .iter()
        .take(max_lines)
        .copied()
        .collect::<Vec<_>>()
        .join("\n");
    let more = if lines.len() > max_lines {
        format!(
            "\n… ({} more lines in translation.json)",
            lines.len() - max_lines
        )
    } else {
        String::new()
    };
    format!("```{lang}\n{}{more}\n```\n", shown.replace("```", "ˋˋˋ"))
}

/// The proposal text.
pub fn markdown(r: &Report) -> String {
    let counts = r.counts();
    let n = |f: Fidelity| counts.get(&f).copied().unwrap_or(0);
    let total: usize = counts.values().sum();
    let mut s = format!(
        "# Pentaho package `{}` → silver and gold dbt models\n\n\
         Generated by EKOS Lakehouse (RFC 0204). **EKOS does not merge this: merging it is the approval.**\n\
         Read every *rewritten* and *llm-drafted* step below before merging; a *gap* is a step that was not translated, \
         and every model that depends on one is written disabled.\n\n\
         | Steps | exact | rewritten | llm-drafted | gap |\n|---|---|---|---|---|\n| {total} | {} | {} | {} | {} |\n\n",
        r.package,
        n(Fidelity::Exact),
        n(Fidelity::Rewritten),
        n(Fidelity::LlmDrafted),
        n(Fidelity::Gap)
    );
    s.push_str("## Models\n\n| Model | Layer | From | Materialization | Fidelity | Enabled |\n|---|---|---|---|---|---|\n");
    for m in &r.models {
        let layer = match m.layer {
            Layer::Silver => "silver",
            Layer::Gold => "gold",
            Layer::Test => "test",
        };
        s.push_str(&format!(
            "| `{}` | {layer} | `{}` | {} | {} | {} |\n",
            m.name,
            cell(&m.transformation),
            m.materialization,
            m.fidelity.as_str(),
            if m.enabled { "yes" } else { "**no**" }
        ));
    }
    if !r.inlined.is_empty() {
        s.push_str(&format!(
            "\nSub-transformations translated where they are used (Mapping): {}\n",
            r.inlined
                .iter()
                .map(|p| format!("`{p}`"))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    if !r.questions.is_empty() {
        s.push_str("\n## Questions\n\nNo SQL is written for a branch until these are answered (map the table in `ekos.toml`, or add it to the lakehouse).\n\n");
        for q in &r.questions {
            s.push_str(&format!(
                "- `{}` / **{}**: {}\n",
                q.transformation,
                cell(&q.step),
                q.question
            ));
        }
    }
    let gaps: Vec<_> = r
        .steps
        .iter()
        .filter(|x| {
            x.fidelity == Fidelity::Gap && !x.gap.as_deref().unwrap_or("").starts_with("depends on")
        })
        .collect();
    if !gaps.is_empty() {
        s.push_str("\n## Not translated\n\nEach step below stops its branch; steps downstream of it are disabled with it.\n\n");
        for g in gaps {
            s.push_str(&format!(
                "### `{}` — {} ({})\n\n{}\n\n",
                g.step,
                g.step_type,
                g.transformation,
                g.gap.as_deref().unwrap_or("")
            ));
            if !g.original.trim().is_empty() {
                s.push_str(&fence(
                    &g.original,
                    if g.category == "code" { "java" } else { "xml" },
                    30,
                ));
                s.push('\n');
            }
        }
    }
    let reviewed: Vec<_> = r
        .steps
        .iter()
        .filter(|x| matches!(x.fidelity, Fidelity::Rewritten | Fidelity::LlmDrafted))
        .collect();
    if !reviewed.is_empty() {
        s.push_str(
            "\n## To review\n\n| Transformation | Step | Fidelity | Why |\n|---|---|---|---|\n",
        );
        for x in reviewed {
            s.push_str(&format!(
                "| `{}` | {} | {} | {} |\n",
                cell(&x.transformation),
                cell(&x.step),
                x.fidelity.as_str(),
                cell(&x.notes.join("; "))
            ));
        }
    }
    s
}
