/// The header of every generated file.
pub const HEADER: &str =
    "-- Generated by ekos-lakehouse (RFC 0204) from a Pentaho package. Do not edit: regenerate.";

/// Translation settings.
#[derive(Debug, Clone, Default)]
pub struct Settings {
    /// The package's name (a `[[sources]]` entry or `pentaho-packages` key).
    pub package: String,
    pub source_database: Option<String>,
    /// Kettle reads `''` as null (RFC 0202): silver models apply `nullif(c, '')`.
    pub empty_string_is_null: bool,
    /// Decompiled `processRow` source per plugin step type, from a `JavaDecompiler`
    /// (RFC 0203); empty in the public build.
    pub plugin_code: BTreeMap<String, String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Layer {
    Silver,
    Gold,
    Test,
}

/// One step of the package as a reviewer sees it.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct StepReport {
    /// `<transformation path>:<step>`: unique across the package (step names repeat).
    #[serde(default)]
    pub id: String,
    pub transformation: String,
    pub step: String,
    /// Ids of the steps feeding this one (for the console's graph).
    #[serde(default)]
    pub inputs: Vec<String>,
    pub step_type: String,
    pub category: String,
    pub branch: Option<String>,
    pub layer: Option<Layer>,
    pub models: Vec<String>,
    pub fidelity: Fidelity,
    pub notes: Vec<String>,
    pub gap: Option<String>,
    /// The step's own text: its code for a code step, its configuration otherwise.
    pub original: String,
    /// The SQL this step became (one CTE), when it was translated.
    pub sql: Option<String>,
    pub line: u32,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ModelReport {
    pub name: String,
    pub layer: Layer,
    pub path: String,
    pub transformation: String,
    pub fidelity: Fidelity,
    pub enabled: bool,
    pub materialization: String,
    /// The table Pentaho wrote, for a gold model.
    pub target: Option<String>,
    pub steps: Vec<String>,
    /// Why the model is disabled.
    pub gaps: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Question {
    pub transformation: String,
    pub step: String,
    pub question: String,
}

/// Everything a translation decided, written as `pentaho/<package>/translation.json`.
#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
pub struct Report {
    pub package: String,
    pub transformations: Vec<String>,
    /// Transformations only used as Mappings: translated where they are used.
    pub inlined: Vec<String>,
    pub steps: Vec<StepReport>,
    pub models: Vec<ModelReport>,
    pub questions: Vec<Question>,
    /// Jobs and their order (kept for the orchestrator; RFC 0204 writes no job models).
    pub jobs: Vec<String>,
}

impl Report {
    /// Steps per fidelity.
    pub fn counts(&self) -> BTreeMap<Fidelity, usize> {
        let mut m = BTreeMap::new();
        for s in &self.steps {
            *m.entry(s.fidelity).or_default() += 1;
        }
        m
    }
}

pub struct Translation {
    /// Path in the pipeline repository → content.
    pub files: BTreeMap<String, String>,
    pub report: Report,
}

/// A dbt-safe slug.
pub fn slug(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('_') {
            out.push('_');
        }
    }
    let out = out.trim_matches('_').to_string();
    if out.is_empty() { "x".into() } else { out }
}

fn file_stem(path: &str) -> String {
    let name = path.rsplit('/').next().unwrap_or(path);
    slug(name.rsplit_once('.').map(|(s, _)| s).unwrap_or(name))
}

/// A step's own text for the report: its code, or its configuration as XML.
pub fn original_text(step: &Step) -> String {
    let x = &step.xml;
    let code = match step.type_id.as_str() {
        "ScriptValueMod" => x.at("jsScripts").map(|s| {
            s.children_named("jsScript")
                .filter_map(|j| j.raw_at("jsScript_script").map(str::to_string))
                .collect::<Vec<_>>()
                .join("\n\n")
        }),
        "UserDefinedJavaClass" => x.at("definitions").map(|d| {
            d.children_named("definition")
                .filter_map(|j| j.raw_at("class_source").map(str::to_string))
                .collect::<Vec<_>>()
                .join("\n\n")
        }),
        "Janino" | "Formula" => Some(
            x.children_named("formula")
                .map(|f| {
                    format!(
                        "{} = {}",
                        f.text_at("field_name").unwrap_or_default(),
                        f.raw_at("formula_string").unwrap_or_default()
                    )
                })
                .collect::<Vec<_>>()
                .join("\n"),
        ),
        "JavaFilter" => x.raw_at("condition").map(str::to_string),
        "TableInput" | "ExecSQL" => x.raw_at("sql").map(str::to_string),
        _ => None,
    };
    code.unwrap_or_else(|| xml_text(x, 0))
}

fn xml_text(n: &ekos_lakehouse_kettle::xml::Node, depth: usize) -> String {
    const SKIP: &[&str] = &[
        "partitioning",
        "remotesteps",
        "cluster_schema",
        "custom_distribution",
        "attributes",
    ];
    let pad = "  ".repeat(depth);
    if n.children.is_empty() {
        return format!("{pad}<{0}>{1}</{0}>", n.name, n.text.trim());
    }
    let inner: Vec<String> = n
        .children
        .iter()
        .filter(|c| !SKIP.contains(&c.name.as_str()))
        .map(|c| xml_text(c, depth + 1))
        .collect();
    format!("{pad}<{0}>\n{1}\n{pad}</{0}>", n.name, inner.join("\n"))
}

/// Where a model lives: (schema, alias).
type Locations = BTreeMap<String, (String, String)>;

struct ModelOut {
    report: ModelReport,
    files: Vec<(String, String)>,
    location: (String, String),
}

/// Translates `package` against the deployed `plan`.
pub fn translate(package: &Package, plan: &Plan, s: &Settings) -> Translation {
    let pkg = slug(&s.package);
    let inlined: BTreeSet<String> = package
        .transformations
        .iter()
        .filter(|t| t.steps.iter().any(|st| st.type_id == "MappingInput"))
        .map(|t| t.path.clone())
        .collect();
    let targets: Vec<&Transformation> = package
        .transformations
        .iter()
        .filter(|t| !inlined.contains(&t.path))
        .collect();

    // Tables the package writes become refs to their gold models: iterate to a fixpoint.
    let mut written: BTreeMap<TableKey, (String, Vec<Field>)> = BTreeMap::new();
    let mut irs: Vec<Ir> = Vec::new();
    for _ in 0..5 {
        let resolver = Resolver {
            plan,
            source_database: s.source_database.clone(),
            written: written.clone(),
        };
        irs = targets
            .iter()
            .map(|t| build_with(package, t, &resolver, &s.plugin_code))
            .collect();
        let next = sink_tables(&irs);
        if next == written {
            break;
        }
        written = next;
    }
    let resolver = Resolver {
        plan,
        source_database: s.source_database.clone(),
        written,
    };

    let mut report = Report {
        package: s.package.clone(),
        transformations: targets.iter().map(|t| t.path.clone()).collect(),
        inlined: inlined.into_iter().collect(),
        jobs: package.jobs.iter().map(|j| j.path.clone()).collect(),
        ..Report::default()
    };
    let mut files = BTreeMap::new();
    let mut locations: Locations = BTreeMap::new();
    for (t, ir) in targets.iter().zip(irs.iter_mut()) {
        let out = translate_one(
            package,
            t,
            ir,
            &resolver,
            s,
            &pkg,
            &mut report,
            &mut locations,
        );
        for m in out {
            for (p, c) in m.files {
                files.insert(p, c);
            }
            locations.insert(m.report.name.clone(), m.location);
            report.models.push(m.report);
        }
    }
    // A model whose SQL does not parse as Trino is disabled (a translator bug must never ship
    // as an enabled model).
    let names: Vec<String> = report
        .models
        .iter()
        .filter(|m| m.enabled)
        .map(|m| m.name.clone())
        .collect();
    for name in names {
        let Some(m) = report.models.iter().find(|m| m.name == name) else {
            continue;
        };
        let Some(sql) = files.get(&m.path) else {
            continue;
        };
        if let Err(e) = parses_as_trino(&engine_sql(sql, &locations, plan)) {
            let path = m.path.clone();
            let disabled = disable(
                sql,
                &[format!("the generated SQL does not parse as Trino: {e}")],
            );
            files.insert(path, disabled);
            if let Some(m) = report.models.iter_mut().find(|m| m.name == name) {
                m.enabled = false;
                m.gaps
                    .push(format!("the generated SQL does not parse as Trino: {e}"));
            }
        }
    }
    report.models.sort_by(|a, b| a.name.cmp(&b.name));
    files.insert(
        format!("pentaho/{pkg}/translation.json"),
        serde_json::to_string_pretty(&report).expect("serializable") + "\n",
    );
    files.insert(
        format!("proposals/pentaho-{pkg}.md"),
        proposal::markdown(&report),
    );
    Translation { files, report }
}

/// Every sink's target table → its gold model and output fields.
fn sink_tables(irs: &[Ir]) -> BTreeMap<TableKey, (String, Vec<Field>)> {
    let mut out = BTreeMap::new();
    for ir in irs {
        for n in &ir.nodes {
            let Op::Sink { sink } = &n.op else { continue };
            let model = format!("gold__{}", slug(&sink.target.table));
            let input = &ir.node(n.inputs[0]).schema;
            let mut fields: Vec<Field> = sink
                .columns
                .iter()
                .chain(sink.keys.iter())
                .filter_map(|(stream, col)| {
                    input.iter().find(|f| &f.name == stream).map(|f| Field {
                        name: col.clone(),
                        ..f.clone()
                    })
                })
                .collect();
            let mut seen = BTreeSet::new();
            fields.retain(|f| seen.insert(f.name.to_lowercase()));
            if let Some(scd) = &sink.scd {
                fields.insert(0, Field::new(&scd.technical_key, KType::String));
                if let Some(v) = &scd.version {
                    fields.push(Field::new(v, KType::Integer));
                }
                for c in [&scd.date_from, &scd.date_to].into_iter().flatten() {
                    fields.push(Field::new(c, KType::Timestamp));
                }
            }
            out.entry(key(&sink.target)).or_insert((model, fields));
        }
    }
    out
}

fn table_of(
    name: &sqlparser::ast::ObjectName,
    conn: Option<&ekos_lakehouse_kettle::Connection>,
) -> TableRef {
    let parts: Vec<String> = name
        .0
        .iter()
        .map(|i| {
            if i.quote_style.is_none() {
                i.value.to_lowercase()
            } else {
                i.value.clone()
            }
        })
        .collect();
    let (schema, table) = match parts.as_slice() {
        [t] => (None, t.clone()),
        [.., s, t] => (Some(s.clone()), t.clone()),
        [] => (None, String::new()),
    };
    TableRef {
        connection: conn.cloned(),
        schema: schema.or_else(|| conn.and_then(|c| c.schema.clone())),
        table,
    }
}

/// Header comment + `enabled=false`: a model that must not run, listed with its reasons.
fn disable(sql: &str, gaps: &[String]) -> String {
    let mut out = format!("{HEADER}\n-- DISABLED: not fully translated.\n");
    for g in gaps {
        for line in g.lines() {
            out.push_str(&format!("--   {line}\n"));
        }
    }
    out.push_str("{{ config(enabled=false) }}\n\n");
    // Keep whatever SQL exists, commented, so the reviewer sees how far it got.
    for line in sql
        .lines()
        .filter(|l| !l.starts_with("--") && !l.starts_with("{{ config("))
    {
        out.push_str(&format!("-- {line}\n"));
    }
    out
}

#[allow(clippy::too_many_arguments)]
fn translate_one(
    package: &Package,
    t: &Transformation,
    ir: &mut Ir,
    resolver: &Resolver<'_>,
    s: &Settings,
    pkg: &str,
    report: &mut Report,
    locations: &mut Locations,
) -> Vec<ModelOut> {
    let trans = file_stem(&t.path);
    let mut source_sql: BTreeMap<NodeId, String> = BTreeMap::new();
    let mut blocked: BTreeMap<NodeId, String> = BTreeMap::new();
    let mut rewrite_notes: BTreeMap<NodeId, Vec<String>> = BTreeMap::new();

    // Dimension lookups against a dimension this package builds: its key is dbt's scd id.
    for n in ir.nodes.iter_mut() {
        if let Op::Lookup {
            table: Some(tbl),
            values,
            valid_at: Some(_),
            ..
        } = &mut n.op
            && matches!(resolver.resolve(tbl), Resolution::Gold { .. })
        {
            for v in values.iter_mut() {
                v.ty = KType::String;
                v.default = Some(Expr::str("0"));
            }
            n.notes.push(
                "unknown member: technical key '0' (the dimension's key is dbt's dbt_scd_id)"
                    .into(),
            );
            n.fidelity = n.fidelity.max(Fidelity::Rewritten);
        }
    }

    // Rewrite every source query; a source that cannot be read blocks its branch.
    for n in &ir.nodes {
        let Op::Source {
            query:
                SourceQuery::Sql {
                    text,
                    tables,
                    limit,
                },
        } = &n.op
        else {
            continue;
        };
        let conn = tables.first().and_then(|t| t.connection.clone());
        let resolve = |name: &sqlparser::ast::ObjectName| -> Result<String, Gap> {
            match resolver.resolve(&table_of(name, conn.as_ref())) {
                Resolution::Silver { model, .. } | Resolution::Gold { model, .. } => Ok(model),
                Resolution::Unknown(why) => Err(Gap::new(why)),
            }
        };
        let rewritten = if conn
            .as_ref()
            .is_some_and(|c| catalog::is_postgres(&c.db_type))
            || tables
                .iter()
                .any(|t| matches!(resolver.resolve(t), Resolution::Gold { .. }))
        {
            pgsql::to_trino(text, &resolve)
        } else {
            let why = tables.first().map(|t| match resolver.resolve(t) {
                Resolution::Unknown(w) => w,
                _ => "the source is not PostgreSQL".into(),
            });
            Err(Gap::new(
                why.unwrap_or_else(|| "the query reads no table".into()),
            ))
        };
        match rewritten {
            Ok(r) => {
                let mut sql = r.sql;
                if let Some(l) = limit {
                    sql = format!("SELECT * FROM ({sql}) AS s LIMIT {l}");
                }
                if s.empty_string_is_null && n.schema.iter().any(|f| f.ty == KType::String) {
                    let items: Vec<String> = n
                        .schema
                        .iter()
                        .map(|f| {
                            if f.ty == KType::String {
                                format!("nullif({0}, '') AS {0}", q(&f.name))
                            } else {
                                q(&f.name)
                            }
                        })
                        .collect();
                    sql = format!("SELECT {} FROM ({sql}) AS s", items.join(", "));
                }
                source_sql.insert(n.id, sql);
                if !r.notes.is_empty() {
                    rewrite_notes.insert(n.id, r.notes);
                }
            }
            Err(g) => {
                if g.reason.contains("not the lakehouse source")
                    || g.reason.contains("not a table of the lakehouse plan")
                {
                    report.questions.push(Question {
                        transformation: t.path.clone(),
                        step: n.step.clone(),
                        question: format!("{} — which lakehouse table holds this data?", g.reason),
                    });
                }
                blocked.insert(n.id, g.reason);
            }
        }
    }
    // Propagate: a node is blocked when it is a gap or reads a blocked node.
    for n in &ir.nodes {
        if let Op::Gap { reason } = &n.op {
            blocked.entry(n.id).or_insert_with(|| reason.clone());
        } else if let Some(i) = n.inputs.iter().find(|i| blocked.contains_key(i)) {
            let why = format!("depends on `{}`, which is not translated", ir.node(*i).step);
            blocked.entry(n.id).or_insert(why);
        }
    }

    // Silver chains.
    let consumers = |id: NodeId| -> Vec<NodeId> {
        ir.nodes
            .iter()
            .filter(|c| c.inputs.contains(&id))
            .map(|c| c.id)
            .collect()
    };
    let mut chain_of: BTreeMap<NodeId, String> = BTreeMap::new();
    let mut chains: Vec<(String, Vec<NodeId>)> = Vec::new();
    for n in &ir.nodes {
        if !matches!(
            n.op,
            Op::Source { .. } | Op::Values { .. } | Op::Generate { .. }
        ) || n.step.contains('/')
        {
            continue;
        }
        let mut chain = vec![n.id];
        let mut cur = n.id;
        loop {
            let c = consumers(cur);
            let [next] = c.as_slice() else { break };
            let nn = ir.node(*next);
            let eligible = matches!(
                nn.op,
                Op::Project { .. }
                    | Op::Filter { .. }
                    | Op::Sort { .. }
                    | Op::Distinct { count: None, .. }
            );
            if !eligible || nn.inputs.len() != 1 {
                break;
            }
            chain.push(*next);
            cur = *next;
        }
        let name = format!("pentaho__{pkg}__{trans}__{}", slug(&n.step));
        for id in &chain {
            chain_of.insert(*id, name.clone());
        }
        chains.push((name, chain));
    }
    let chain_end: BTreeMap<String, NodeId> = chains
        .iter()
        .map(|(n, c)| (n.clone(), *c.last().expect("non-empty")))
        .collect();

    let mut outs = Vec::new();
    let table_ref = |tbl: &TableRef| -> Result<String, Gap> {
        match resolver.resolve(tbl) {
            Resolution::Silver { model, .. } | Resolution::Gold { model, .. } => {
                Ok(format!("{{{{ ref('{model}') }}}}"))
            }
            Resolution::Unknown(why) => Err(Gap::new(why)),
        }
    };
    let node_ref = |id: NodeId| -> Option<String> {
        let model = chain_of.get(&id)?;
        (chain_end.get(model) == Some(&id)).then(|| format!("{{{{ ref('{model}') }}}}"))
    };
    let inputs = render::Inputs {
        node_ref: &node_ref,
        source_sql: &source_sql,
        table_ref: &table_ref,
    };

    // Silver models.
    for (name, chain) in &chains {
        let end = ir.node(*chain.last().expect("non-empty"));
        let gaps: Vec<String> = chain
            .iter()
            .filter_map(|i| blocked.get(i).map(|r| format!("{}: {r}", ir.node(*i).step)))
            .collect();
        let fidelity = chain
            .iter()
            .map(|i| ir.node(*i).fidelity)
            .max()
            .unwrap_or(Fidelity::Exact);
        let path = format!("dbt/models/silver/pentaho/{pkg}/{name}.sql");
        let config = format!(
            "{{{{ config(materialized='table', schema='silver_pentaho', alias='{}') }}}}",
            name.trim_start_matches(&format!("pentaho__{pkg}__"))
        );
        let sql = if gaps.is_empty() {
            match render::model_sql(ir, chain, &select_all(&end.schema), &inputs) {
                Ok(body) => format!("{HEADER}\n{config}\n\n{body}\n"),
                Err(g) => disable("", &[g.reason]),
            }
        } else {
            disable("", &gaps)
        };
        let enabled = !sql.contains("enabled=false");
        let alias = name
            .trim_start_matches(&format!("pentaho__{pkg}__"))
            .to_string();
        outs.push(ModelOut {
            report: ModelReport {
                name: name.clone(),
                layer: Layer::Silver,
                path: path.clone(),
                transformation: t.path.clone(),
                fidelity: if enabled { fidelity } else { Fidelity::Gap },
                enabled,
                materialization: "table".into(),
                target: None,
                steps: chain.iter().map(|i| ir.node(*i).step.clone()).collect(),
                gaps,
            },
            files: vec![(path, sql)],
            location: ("silver_pentaho".into(), alias),
        });
    }

    // Gold models: one per sink; tests: one per Abort.
    let mut taken: BTreeSet<String> = locations.keys().cloned().collect();
    for n in &ir.nodes {
        let is_sink = matches!(n.op, Op::Sink { .. });
        let is_assert = matches!(n.op, Op::Assert { .. });
        if !is_sink && !is_assert {
            continue;
        }
        let input = n.inputs[0];
        // The nodes of this model: upstream of the sink, stopping at silver models.
        let mut ids = BTreeSet::new();
        let mut stack = vec![input];
        while let Some(id) = stack.pop() {
            if chain_of.contains_key(&id) || !ids.insert(id) {
                continue;
            }
            stack.extend(ir.node(id).inputs.iter().copied());
        }
        let ids: Vec<NodeId> = ids.into_iter().collect();
        let mut gaps: Vec<String> = ids
            .iter()
            .filter_map(|i| blocked.get(i).map(|r| format!("{}: {r}", ir.node(*i).step)))
            .collect();
        for (_, c) in chains.iter().filter(|(_, c)| {
            ids.iter()
                .any(|i| ir.node(*i).inputs.contains(c.last().expect("non-empty")))
        }) {
            gaps.extend(
                c.iter()
                    .filter_map(|i| blocked.get(i).map(|r| format!("{}: {r}", ir.node(*i).step))),
            );
        }
        if blocked.contains_key(&input) && ids.is_empty() {
            gaps.push(format!("{}: {}", ir.node(input).step, blocked[&input]));
        }
        let fidelity = ids
            .iter()
            .map(|i| ir.node(*i).fidelity)
            .chain([n.fidelity])
            .max()
            .unwrap_or(Fidelity::Exact);
        let shared = ids.iter().any(|i| {
            ir.nodes.iter().filter(|o| o.inputs.contains(i)).count() > 1
                && !matches!(ir.node(*i).op, Op::Filter { .. })
        });
        if is_assert {
            let Op::Assert { message } = &n.op else {
                unreachable!()
            };
            let name = format!("assert_{pkg}__{trans}__{}", slug(&n.step));
            let path = format!("dbt/tests/pentaho/{pkg}/{name}.sql");
            let body = if gaps.is_empty() {
                render::model_sql(ir, &ids, "*", &inputs).map_err(|g| vec![g.reason])
            } else {
                Err(gaps.clone())
            };
            let (sql, enabled) = match body {
                Ok(b) => (
                    format!(
                        "{HEADER}\n-- Abort step `{}`: {message}. The test fails when any row reaches it.\n\n{b}\n",
                        n.step
                    ),
                    true,
                ),
                Err(g) => (disable("", &g), false),
            };
            outs.push(ModelOut {
                report: ModelReport {
                    name: name.clone(),
                    layer: Layer::Test,
                    path: path.clone(),
                    transformation: t.path.clone(),
                    fidelity: if enabled { fidelity } else { Fidelity::Gap },
                    enabled,
                    materialization: "test".into(),
                    target: None,
                    steps: vec![n.step.clone()],
                    gaps: if enabled { vec![] } else { gaps },
                },
                files: vec![(path, sql)],
                location: (String::new(), name),
            });
            continue;
        }
        let Op::Sink { sink } = &n.op else {
            unreachable!()
        };
        let target = slug(&sink.target.table);
        let name = format!("gold__{target}");
        if !taken.insert(name.clone()) {
            gaps.push(format!(
                "the table `{}` is also written by another transformation of the package",
                sink.target.table
            ));
        }
        let mut notes = Vec::new();
        if shared {
            notes.push(
                "a step feeds several outputs: its SQL is repeated in each gold model".to_string(),
            );
        }
        let mut columns: Vec<(String, String)> = sink.keys.to_vec();
        for c in &sink.columns {
            if !columns
                .iter()
                .any(|(_, col)| col.eq_ignore_ascii_case(&c.1))
            {
                columns.push(c.clone());
            }
        }
        let final_select = columns
            .iter()
            .map(|(s, c)| format!("{} AS {}", q(s), q(c)))
            .collect::<Vec<_>>()
            .join(", ");
        let model_ids: Vec<NodeId> = if ids.is_empty() { vec![] } else { ids.clone() };
        let gold_path = format!("dbt/models/gold/pentaho/{pkg}/{name}.sql");
        let yml_path = format!("dbt/models/gold/pentaho/{pkg}/_{name}.yml");
        let mut files_out = Vec::new();
        let body = if !gaps.is_empty() {
            Err(gaps.clone())
        } else if model_ids.is_empty() {
            // The sink reads a silver model directly.
            match node_ref(input) {
                Some(r) => Ok(format!("SELECT {final_select} FROM {r}")),
                None => Err(vec!["the output reads nothing translated".to_string()]),
            }
        } else {
            render::model_sql(ir, &model_ids, &final_select, &inputs).map_err(|g| vec![g.reason])
        };
        let materialization;
        let mut tests: Vec<String> = Vec::new();
        let sql = match (body, sink.mode) {
            (Err(g), _) => {
                materialization = "table".to_string();
                disable("", &g)
            }
            (Ok(b), SinkMode::Insert) => {
                let (m, cfg) = if sink.truncate {
                    (
                        "table",
                        format!(
                            "{{{{ config(materialized='table', schema='gold', alias='{target}') }}}}"
                        ),
                    )
                } else {
                    notes.push(
                        "Kettle appends on every run: an incremental model that appends".into(),
                    );
                    (
                        "incremental (append)",
                        format!(
                            "{{{{ config(materialized='incremental', incremental_strategy='append', schema='gold', alias='{target}') }}}}"
                        ),
                    )
                };
                materialization = m.to_string();
                format!("{HEADER}\n{cfg}\n\n{b}\n")
            }
            (Ok(b), SinkMode::Upsert | SinkMode::Update) => {
                let keys: Vec<String> = sink.keys.iter().map(|(_, c)| quote_str(c)).collect();
                let update_cols: Vec<String> = sink
                    .columns
                    .iter()
                    .filter(|(s2, c)| {
                        let insert_only = n
                            .notes
                            .iter()
                            .any(|x| x.contains(&format!("`{c}` is written on insert only")));
                        !insert_only && !sink.keys.iter().any(|(_, k)| k == c) && !s2.is_empty()
                    })
                    .map(|(_, c)| quote_str(c))
                    .collect();
                let cfg = format!(
                    "{{{{ config(materialized='incremental', incremental_strategy='merge', unique_key=[{}], merge_update_columns=[{}], schema='gold', alias='{target}') }}}}",
                    keys.join(", "),
                    update_cols.join(", ")
                );
                tests.push(format!(
                    "      - ekos_unique_combination:\n          columns: [{}]",
                    sink.keys
                        .iter()
                        .map(|(_, c)| c.clone())
                        .collect::<Vec<_>>()
                        .join(", ")
                ));
                let body = if sink.mode == SinkMode::Update {
                    notes.push("Update changes existing rows only: rows whose keys are not in the table yet are dropped (the first build is empty)".into());
                    let key_cols: Vec<String> = sink.keys.iter().map(|(_, c)| q(c)).collect();
                    format!(
                        "SELECT * FROM (\n{b}\n) AS u\n{{% if is_incremental() %}}WHERE ({k}) IN (SELECT {k} FROM {{{{ this }}}}){{% else %}}WHERE FALSE{{% endif %}}",
                        k = key_cols.join(", ")
                    )
                } else {
                    b
                };
                materialization = "incremental (merge)".to_string();
                format!("{HEADER}\n{cfg}\n\n{body}\n")
            }
            (Ok(_), SinkMode::Delete) => {
                materialization = "table".to_string();
                disable("", &["Delete removes rows from a table another model builds; there is no dbt model for it".into()])
            }
            (Ok(b), SinkMode::Dimension) => {
                let scd = sink.scd.as_ref().expect("dimension has scd");
                materialization = "snapshot + table".to_string();
                let stage = format!("pentaho__{pkg}__{target}_stage");
                let snap = format!("pentaho__{pkg}__{target}_snapshot");
                let stage_sql = format!(
                    "{HEADER}\n{{{{ config(materialized='table', schema='gold', alias='{target}_stage') }}}}\n\n{b}\n"
                );
                files_out.push((
                    format!("dbt/models/gold/pentaho/{pkg}/{stage}.sql"),
                    stage_sql,
                ));
                locations.insert(stage.clone(), ("gold".into(), format!("{target}_stage")));
                let key_cols: Vec<String> = sink.keys.iter().map(|(_, c)| c.clone()).collect();
                let type2: Vec<String> = scd
                    .field_modes
                    .iter()
                    .filter(|(_, m)| m == "insert")
                    .map(|(c, _)| c.clone())
                    .collect();
                let type1: Vec<String> = scd
                    .field_modes
                    .iter()
                    .filter(|(_, m)| m != "insert")
                    .map(|(c, _)| c.clone())
                    .collect();
                let check = if type2.is_empty() {
                    key_cols.clone()
                } else {
                    type2.clone()
                };
                let ekos_key = key_cols
                    .iter()
                    .map(|k| format!("coalesce(CAST({} AS varchar), '')", q(k)))
                    .collect::<Vec<_>>()
                    .join(" || '|' || ");
                let snap_sql = format!(
                    "{HEADER}\n{{% snapshot {snap} %}}\n{{{{ config(target_schema='snapshots_pentaho', unique_key='ekos_key', strategy='check', check_cols=[{}]) }}}}\nSELECT {ekos_key} AS ekos_key, * FROM {{{{ ref('{stage}') }}}}\n{{% endsnapshot %}}\n",
                    check
                        .iter()
                        .map(|c| quote_str(c))
                        .collect::<Vec<_>>()
                        .join(", ")
                );
                files_out.push((format!("dbt/snapshots/pentaho/{pkg}/{snap}.sql"), snap_sql));
                let part = key_cols
                    .iter()
                    .map(|k| format!("s.{}", q(k)))
                    .collect::<Vec<_>>()
                    .join(", ");
                let mut sel = vec![format!("s.dbt_scd_id AS {}", q(&scd.technical_key))];
                if let Some(v) = &scd.version {
                    sel.push(format!(
                        "row_number() OVER (PARTITION BY {part} ORDER BY s.dbt_valid_from) AS {}",
                        q(v)
                    ));
                }
                if let Some(f) = &scd.date_from {
                    sel.push(format!(
                        "CAST(s.dbt_valid_from AS timestamp(6)) AS {}",
                        q(f)
                    ));
                }
                if let Some(to) = &scd.date_to {
                    sel.push(format!("coalesce(CAST(s.dbt_valid_to AS timestamp(6)), TIMESTAMP '2199-12-31 00:00:00.000000') AS {}", q(to)));
                }
                sel.extend(key_cols.iter().map(|k| format!("s.{}", q(k))));
                sel.extend(type2.iter().map(|c| format!("s.{}", q(c))));
                sel.extend(type1.iter().map(|c| format!("c.{0} AS {0}", q(c))));
                let on = key_cols
                    .iter()
                    .map(|k| format!("c.{0} = s.{0}", q(k)))
                    .collect::<Vec<_>>()
                    .join(" AND ");
                notes.push("dimension: a dbt snapshot keeps the type 2 history; the technical key is dbt_scd_id (a hash), type 1 columns carry the latest value".into());
                tests.push(format!(
                    "    columns:\n      - name: {}\n        tests: [unique, not_null]",
                    scd.technical_key
                ));
                format!(
                    "{HEADER}\n{{{{ config(materialized='table', schema='gold', alias='{target}') }}}}\n\nSELECT {}\nFROM {{{{ ref('{snap}') }}}} AS s\nLEFT JOIN {{{{ ref('{stage}') }}}} AS c ON {on}\n",
                    sel.join(",\n       ")
                )
            }
            (Ok(_), SinkMode::Combination) => {
                materialization = "table".to_string();
                disable("", &["Combination lookup/update is not translated".into()])
            }
        };
        let enabled = !sql.contains("enabled=false");
        files_out.push((gold_path.clone(), sql));
        let mut yml = format!(
            "# Generated by ekos-lakehouse (RFC 0204). Do not edit: regenerate.\nversion: 2\nmodels:\n  - name: {name}\n    description: \"Pentaho `{}` → `{}` ({})\"\n    group: gold\n",
            n.step, sink.target.table, t.path
        );
        if enabled {
            for tst in tests
                .iter()
                .filter(|x| x.trim_start().starts_with("- ekos_unique"))
            {
                yml.push_str(&format!("    tests:\n{tst}\n"));
            }
            for tst in tests
                .iter()
                .filter(|x| x.trim_start().starts_with("columns:"))
            {
                yml.push_str(&format!("{tst}\n"));
            }
        }
        files_out.push((yml_path, yml));
        outs.push(ModelOut {
            report: ModelReport {
                name: name.clone(),
                layer: Layer::Gold,
                path: gold_path,
                transformation: t.path.clone(),
                fidelity: if enabled { fidelity } else { Fidelity::Gap },
                enabled,
                materialization,
                target: Some(sink.target.table.clone()),
                steps: ids
                    .iter()
                    .map(|i| ir.node(*i).step.clone())
                    .chain([n.step.clone()])
                    .collect(),
                gaps: if enabled { vec![] } else { gaps },
            },
            files: files_out,
            location: ("gold".into(), target.clone()),
        });
        for note in notes {
            report.steps.push(StepReport {
                id: format!("{}:{} (model {name})", t.path, n.step),
                inputs: vec![format!("{}:{}", t.path, n.step)],
                transformation: t.path.clone(),
                step: n.step.clone(),
                step_type: "(model)".into(),
                category: "model".into(),
                branch: None,
                layer: Some(Layer::Gold),
                models: vec![name.clone()],
                fidelity: Fidelity::Rewritten,
                notes: vec![note],
                gap: None,
                original: String::new(),
                sql: None,
                line: n.line,
            });
        }
    }

    // Per-step report.
    let models_of = |id: NodeId| -> Vec<String> {
        outs.iter()
            .filter(|m| m.report.steps.contains(&ir.node(id).step))
            .map(|m| m.report.name.clone())
            .collect()
    };
    for n in &ir.nodes {
        if n.step.ends_with(" (inputs)") {
            continue;
        }
        let step = step_for(package, t, &n.step);
        let input = |i: NodeId| render::cte_name(ir.node(i));
        let sql = if blocked.contains_key(&n.id) {
            None
        } else {
            render::node_sql(ir, n, &input, &inputs).ok()
        };
        let layer = if chain_of.contains_key(&n.id) {
            Some(Layer::Silver)
        } else if matches!(n.op, Op::Assert { .. }) {
            Some(Layer::Test)
        } else if models_of(n.id).is_empty() {
            None
        } else {
            Some(Layer::Gold)
        };
        let gap = blocked.get(&n.id).cloned();
        // A synthetic union of several hops stands for its inputs.
        let mut inputs = Vec::new();
        for i in &n.inputs {
            let up = ir.node(*i);
            let ids: Vec<NodeId> = if up.step.ends_with(" (inputs)") {
                up.inputs.clone()
            } else {
                vec![*i]
            };
            for id in ids {
                let s = format!("{}:{}", t.path, ir.node(id).step);
                if !inputs.contains(&s) && ir.node(id).step != n.step {
                    inputs.push(s);
                }
            }
        }
        report.steps.push(StepReport {
            id: format!("{}:{}", t.path, n.step),
            inputs,
            transformation: t.path.clone(),
            step: n.step.clone(),
            step_type: n.step_type.clone(),
            category: step
                .map(|s| s.category.as_str())
                .unwrap_or(Category::Unknown.as_str())
                .to_string(),
            branch: n.branch.clone(),
            layer,
            models: models_of(n.id),
            fidelity: if gap.is_some() {
                Fidelity::Gap
            } else if rewrite_notes.contains_key(&n.id) {
                n.fidelity.max(Fidelity::Rewritten)
            } else {
                n.fidelity
            },
            notes: n
                .notes
                .iter()
                .chain(rewrite_notes.get(&n.id).into_iter().flatten())
                .cloned()
                .collect(),
            gap,
            original: match step {
                Some(st) if s.plugin_code.contains_key(&st.type_id) => format!(
                    "// decompiled from the plugin's jar (a reconstruction, not its source)\n{}",
                    s.plugin_code[&st.type_id]
                ),
                Some(st) => original_text(st),
                None => String::new(),
            },
            sql,
            line: n.line,
        });
    }
    outs
}

/// The Kettle step behind an IR node (inlined steps are `mapping/step` in a child file).
fn step_for<'a>(package: &'a Package, t: &'a Transformation, name: &str) -> Option<&'a Step> {
    if let Some(s) = t.step(name) {
        return Some(s);
    }
    let (mapping, rest) = name.split_once('/')?;
    let link = package
        .links
        .iter()
        .find(|l| l.from == t.path && l.via == mapping)?;
    let child = package.transformation(link.to.as_deref()?)?;
    step_for(package, child, rest)
}

fn select_all(schema: &[Field]) -> String {
    if schema.is_empty() {
        "*".into()
    } else {
        schema
            .iter()
            .map(|f| q(&f.name))
            .collect::<Vec<_>>()
            .join(", ")
    }
}

/// A model's SQL as the engine runs it: config and comments dropped, every `ref()` replaced by
/// its physical table (silver source models, and the package's own models).
pub fn engine_sql(
    sql: &str,
    locations: &BTreeMap<String, (String, String)>,
    plan: &Plan,
) -> String {
    let mut out = String::new();
    let mut rest = sql;
    while let Some(i) = rest.find("{{ ref('") {
        out.push_str(&rest[..i]);
        let after = &rest[i + "{{ ref('".len()..];
        let Some(j) = after.find("') }}") else { break };
        let model = &after[..j];
        let (schema, table) = match locations.get(model) {
            Some((s, a)) => (s.clone(), a.clone()),
            None => match plan
                .tables
                .iter()
                .find(|t| ekos_lakehouse_silver::model_name(t) == model)
            {
                Some(t) => (ekos_lakehouse_silver::silver_schema(t), t.table.clone()),
                None => ("unknown".into(), model.to_string()),
            },
        };
        out.push_str(&format!("{}.{}.{}", q("iceberg"), q(&schema), q(&table)));
        rest = &after[j + "') }}".len()..];
    }
    out.push_str(rest);
    out.lines()
        .filter(|l| !l.starts_with("--") && !l.starts_with("{{ config(") && !l.starts_with("{%"))
        .map(|l| {
            // Jinja inside a line (Update's incremental filter): keep the first-build branch.
            if let Some(i) = l.find("{% if is_incremental() %}") {
                let tail = l[i..]
                    .split("{% else %}")
                    .nth(1)
                    .unwrap_or("")
                    .replace("{% endif %}", "");
                format!("{}{}", &l[..i], tail)
            } else {
                l.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Whether `sql` parses with the Trino grammar.
pub fn parses_as_trino(sql: &str) -> Result<(), String> {
    use ekos_sql_dialect_sdk::SqlDialectParser;
    let trino = ekos_plugin_sql_dialect_trino::TrinoDialectParser;
    let pre = trino.preprocess(sql);
    sqlparser::parser::Parser::parse_sql(&*trino.sqlparser_dialect(), &pre)
        .map(|_| ())
        .map_err(|e| e.to_string())
}

/// A model's SQL that Trino can plan (and run) before any model of the package is built: every
/// `ref()` to a model of the package is inlined as a sub-query — a snapshot as its first build
/// would be (one open version per key) — and every other `ref()` is the silver table it names.
/// For `EXPLAIN`, and for running a translation against a sandbox without dbt.
pub fn plannable_sql(
    name: &str,
    files: &BTreeMap<String, String>,
    plan: &Plan,
) -> Result<String, String> {
    let by_name: BTreeMap<String, &String> = files
        .iter()
        .filter(|(p, _)| {
            p.ends_with(".sql")
                && (p.starts_with("dbt/models/")
                    || p.starts_with("dbt/snapshots/")
                    || p.starts_with("dbt/tests/"))
        })
        .map(|(p, body)| {
            (
                p.rsplit('/')
                    .next()
                    .unwrap_or(p)
                    .trim_end_matches(".sql")
                    .to_string(),
                body,
            )
        })
        .collect();
    fn body_of(sql: &str) -> String {
        let mut lines: Vec<&str> = sql
            .lines()
            .filter(|l| {
                !l.starts_with("--")
                    && !l.trim_start().starts_with("{{ config(")
                    && !l.starts_with("{% snapshot")
                    && !l.starts_with("{% endsnapshot")
            })
            .collect();
        while lines.first().is_some_and(|l| l.trim().is_empty()) {
            lines.remove(0);
        }
        lines.join("\n")
    }
    fn expand(
        sql: &str,
        by_name: &BTreeMap<String, &String>,
        plan: &Plan,
        depth: usize,
    ) -> Result<String, String> {
        if depth > 16 {
            return Err("models reference each other too deeply".into());
        }
        let mut out = String::new();
        let mut rest = sql;
        while let Some(i) = rest.find("{{ ref('") {
            out.push_str(&rest[..i]);
            let after = &rest[i + "{{ ref('".len()..];
            let j = after.find("') }}").ok_or("an unclosed ref")?;
            let model = &after[..j];
            match by_name.get(model) {
                Some(body) if body.contains("{% snapshot") => {
                    let inner = expand(&body_of(body), by_name, plan, depth + 1)?;
                    out.push_str(&format!(
                        "(SELECT x.*, x.ekos_key AS dbt_scd_id, TIMESTAMP '1900-01-01 00:00:00.000000' AS dbt_valid_from, CAST(NULL AS timestamp(6)) AS dbt_valid_to FROM ({inner}) AS x)"
                    ));
                }
                Some(body) => {
                    if body.contains("enabled=false") {
                        return Err(format!("it reads `{model}`, which is disabled"));
                    }
                    out.push_str(&format!(
                        "({})",
                        expand(&body_of(body), by_name, plan, depth + 1)?
                    ));
                }
                None => match plan
                    .tables
                    .iter()
                    .find(|t| ekos_lakehouse_silver::model_name(t) == model)
                {
                    Some(t) => out.push_str(&format!(
                        "{}.{}.{}",
                        q(&plan.settings.target_catalog),
                        q(&ekos_lakehouse_silver::silver_schema(t)),
                        q(&t.table)
                    )),
                    None => {
                        return Err(format!(
                            "`{model}` is neither a package model nor a silver model"
                        ));
                    }
                },
            }
            rest = &after[j + "') }}".len()..];
        }
        out.push_str(rest);
        Ok(out)
    }
    let body = by_name
        .get(name)
        .ok_or_else(|| format!("no model {name}"))?;
    let sql = expand(&body_of(body), &by_name, plan, 0)?;
    // Update's incremental filter: plan the first build.
    let sql = match (
        sql.find("{% if is_incremental() %}"),
        sql.find("{% else %}"),
    ) {
        (Some(i), Some(e)) => {
            let end = sql.find("{% endif %}").unwrap_or(sql.len());
            format!("{}{}", &sql[..i], &sql[e + "{% else %}".len()..end])
        }
        _ => sql,
    };
    Ok(sql)
}

