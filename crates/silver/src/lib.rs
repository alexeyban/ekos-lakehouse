/// Every file of the silver dbt project, by path under the pipeline repository.
pub fn files(plan: &Plan, s: &SilverSettings) -> (BTreeMap<String, String>, SilverReport) {
    let mut out = BTreeMap::new();
    let mut report = SilverReport::default();
    let mut project = DBT_PROJECT.to_string();
    if s.pii.values().any(|m| *m == MaskMethod::Hmac) {
        // No default: without the key dbt refuses to run, rather than hashing with an empty one.
        project.push_str(
            "vars:\n  # The masking key (RFC 0193 §2), from the environment; never written here.\n  \
             ekos_pii_key: \"{{ env_var('EKOS_LH_PII_KEY') }}\"\n",
        );
    }
    out.insert("dbt/dbt_project.yml".into(), project);
    out.insert("dbt/profiles.yml".into(), PROFILES.into());
    out.insert("dbt/.sqlfluff".into(), SQLFLUFF.into());
    out.insert("dbt/.gitignore".into(), GITIGNORE.into());
    out.insert(
        "dbt/macros/generate_schema_name.sql".into(),
        SCHEMA_MACRO.into(),
    );
    out.insert(
        "dbt/tests/generic/ekos_unique_combination.sql".into(),
        UNIQUE_COMBINATION.into(),
    );
    out.insert(
        "dbt/models/bronze_sources.yml".into(),
        yaml(&sources_yaml(plan)),
    );

    let mut by_schema: BTreeMap<&str, Vec<Value>> = BTreeMap::new();
    let mut snapshots: Vec<Value> = vec![];
    for t in &plan.tables {
        let dir = format!("dbt/models/silver/{}", t.schema);
        out.insert(
            format!("{dir}/{}.sql", model_name(t)),
            model_sql(t, s, &mut report),
        );
        by_schema
            .entry(t.schema.as_str())
            .or_default()
            .push(model_yaml(t, plan, s, &mut report));
        if s.history.contains(&format!("{}.{}", t.schema, t.table)) && !t.primary_key.is_empty() {
            snapshots.push(snapshot_yaml(t));
        }
    }
    for (schema, models) in by_schema {
        let mut root = Mapping::new();
        root.insert("version".into(), 2.into());
        root.insert("models".into(), Value::Sequence(models));
        out.insert(
            format!("dbt/models/silver/{schema}/_{schema}__models.yml"),
            yaml(&Value::Mapping(root)),
        );
    }
    if !snapshots.is_empty() {
        let mut root = Mapping::new();
        root.insert("version".into(), 2.into());
        root.insert("snapshots".into(), Value::Sequence(snapshots));
        out.insert(
            "dbt/snapshots/_snapshots.yml".into(),
            yaml(&Value::Mapping(root)),
        );
    }
    report.pii_candidates.sort();
    report.skipped_foreign_keys.sort();
    (out, report)
}

