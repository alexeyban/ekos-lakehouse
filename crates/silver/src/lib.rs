    #[test]
    fn tests_come_from_facts_and_duplicate_keys_test_once() {
        let (f, r) = files(&the_plan(), &settings());
        let y = &f["dbt/models/silver/public/_public__models.yml"];
        let doc: Value = serde_yaml::from_str(y).unwrap();
        let models = doc["models"].as_sequence().unwrap();
        let film = models.iter().find(|m| m["name"] == "public__film").unwrap();
        assert_eq!(film["description"], "A film.");
        let cols = film["columns"].as_sequence().unwrap();
        let lang = cols.iter().find(|c| c["name"] == "language_id").unwrap();
        let rels: Vec<&Value> = lang["data_tests"]
            .as_sequence()
            .unwrap()
            .iter()
            .filter(|t| t.get("relationships").is_some())
            .collect();
        assert_eq!(rels.len(), 1, "two declarations of one key, one test: {lang:?}");
        assert!(
            serde_yaml::to_string(rels[0])
                .unwrap()
                .contains("film_language_fk, film_language_fk_again")
        );
        let rating = cols.iter().find(|c| c["name"] == "rating").unwrap();
        assert!(serde_yaml::to_string(rating).unwrap().contains("accepted_values"));
        assert_eq!(
            r.skipped_foreign_keys,
            ["public.film film_studio_fk: public.studio is not planned"]
        );
        let customer = models.iter().find(|m| m["name"] == "public__customer").unwrap();
        assert!(
            serde_yaml::to_string(&customer["data_tests"])
                .unwrap()
                .contains("ekos_unique_combination"),
            "a composite key is tested as one"
        );
    }

