//! The silver layer (RFC 0193): a dbt-trino project generated from the bronze plan's source
//! facts. One model per bronze table — deduplicated to bronze's current state, approved masks
//! applied — with tests from the catalog (keys, NOT NULL, foreign keys, enum labels), docs from
//! the source's comments, and declared history as snapshots. Pure: the same plan and settings
//! render the same bytes.

use ekos_lakehouse_bronze::LoadMode;
use ekos_lakehouse_bronze::plan::{Plan, TablePlan};
use ekos_lakehouse_bronze::typemap::ident;
use serde::{Deserialize, Serialize};
use serde_yaml::{Mapping, Value};
use std::collections::BTreeMap;

const HEADER: &str = "-- Generated by ekos-lakehouse (RFC 0193). Do not edit: regenerate.\n";
const YAML_HEADER: &str = "# Generated by ekos-lakehouse (RFC 0193). Do not edit: regenerate.\n";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MaskMethod {
    /// The column stays; its values do not.
    Null,
    /// HMAC-SHA256 under the key in `EKOS_LH_PII_KEY`, lowercase hex.
    Hmac,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case", default)]
pub struct SilverSettings {
    /// Approved masks: `"schema.table.column" = "null" | "hmac"` (RFC 0193 §2).
    pub pii: BTreeMap<String, MaskMethod>,
    /// `"schema.table"` entries that get an SCD2 snapshot (RFC 0193 §4).
    pub history: Vec<String>,
}

/// What the generator decided that a person should see.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize)]
pub struct SilverReport {
    /// `schema.table.column (class)` — candidates from the name classifier, not masked.
    pub pii_candidates: Vec<String>,
    pub masked: Vec<String>,
    /// Foreign keys with no relationship test, and why.
    pub skipped_foreign_keys: Vec<String>,
    /// Silver columns that are computed rather than passed through: lineage expects these.
    pub computed: Vec<String>,
}

pub fn model_name(t: &TablePlan) -> String {
    format!("{}__{}", t.schema, t.table)
}

pub fn silver_schema(t: &TablePlan) -> String {
    format!("silver_{}", t.schema)
}

/// Quote a column for YAML/tests only when dbt would otherwise fold or misread it.
fn needs_quote(name: &str) -> bool {
    !name
        .chars()
        .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        || name.starts_with(|c: char| c.is_ascii_digit())
}

fn column_expr(t: &TablePlan, col: &str, s: &SilverSettings, report: &mut SilverReport) -> String {
    let key = format!("{}.{}.{}", t.schema, t.table, col);
    let id = ident(col);
    let iceberg = t
        .columns
        .iter()
        .find(|m| m.column == col)
        .map(|m| m.iceberg_type.clone())
        .unwrap_or_default();
    match s.pii.get(&key) {
        Some(MaskMethod::Null) => {
            report.masked.push(format!("{key} (null)"));
            report.computed.push(format!("{key}: masked"));
            format!("cast(null as {iceberg}) as {id}")
        }
        Some(MaskMethod::Hmac) => {
            report.masked.push(format!("{key} (hmac)"));
            report.computed.push(format!("{key}: masked"));
            format!(
                "lower(to_hex(hmac_sha256(\n        to_utf8(cast({id} as varchar)),\n        \
                 to_utf8('{{{{ var(\"ekos_pii_key\") }}}}')\n    ))) as {id}"
            )
        }
        None => id,
    }
}

pub fn model_sql(t: &TablePlan, s: &SilverSettings, report: &mut SilverReport) -> String {
    let mut cols: Vec<String> = t
        .columns
        .iter()
        .map(|m| column_expr(t, &m.column, s, report))
        .collect();
    cols.push("\"_ekos_loaded_at\" as \"_ekos_bronze_loaded_at\"".into());
    let select = cols
        .iter()
        .map(|c| format!("    {c}"))
        .collect::<Vec<_>>()
        .join(",\n");
    let config = format!(
        "{{{{ config(materialized='table', schema='{}', alias='{}') }}}}\n\n",
        silver_schema(t),
        t.table.replace('\'', "\\'")
    );
    let source = format!(
        "with bronze as (\n    select * from {{{{ source('{}', '{}') }}}}\n)",
        t.namespace, t.table
    );
    let body = match (&t.decision.mode, t.primary_key.is_empty()) {
        (LoadMode::Full, _) => format!("{source}\n\nselect\n{select}\nfrom bronze\n"),
        (LoadMode::Incremental { .. }, false) => {
            let key = t
                .primary_key
                .iter()
                .map(|k| ident(k))
                .collect::<Vec<_>>()
                .join(", ");
            format!(
                "{source},\n\nlatest as (\n    select\n        *,\n        row_number() over (\n            \
                 partition by {key}\n            order by \"_ekos_loaded_at\" desc\n        ) as \"_ekos_rn\"\n    \
                 from bronze\n)\n\nselect\n{select}\nfrom latest\nwhere \"_ekos_rn\" = 1 and \"_ekos_op\" != 'delete'\n"
            )
        }
        // No key: a re-read row cannot be told from its earlier copy except by its values.
        (LoadMode::Incremental { .. }, true) => format!(
            "{source}\n\nselect distinct\n{select}\nfrom bronze\nwhere \"_ekos_op\" != 'delete'\n"
        ),
    };
    format!("{HEADER}{config}{body}")
}

fn test(name: &str, args: Option<Value>, rule: &str, evidence: &str) -> Value {
    let mut cfg = Mapping::new();
    let mut meta = Mapping::new();
    meta.insert("ekos_rule".into(), rule.into());
    meta.insert("evidence".into(), evidence.into());
    cfg.insert("meta".into(), Value::Mapping(meta));
    let mut body = Mapping::new();
    if let Some(a) = args {
        body.insert("arguments".into(), a);
    }
    body.insert("config".into(), Value::Mapping(cfg));
    let mut t = Mapping::new();
    t.insert(name.into(), Value::Mapping(body));
    Value::Mapping(t)
}

fn model_yaml(t: &TablePlan, plan: &Plan, s: &SilverSettings, report: &mut SilverReport) -> Value {
    let planned: BTreeMap<(String, String), &TablePlan> = plan
        .tables
        .iter()
        .map(|x| ((x.schema.clone(), x.table.clone()), x))
        .collect();
    let mut col_tests: BTreeMap<String, Vec<Value>> = BTreeMap::new();
    let mut model_tests: Vec<Value> = vec![];
    let masked = |c: &str| {
        s.pii
            .contains_key(&format!("{}.{}.{}", t.schema, t.table, c))
    };

    match t.primary_key.as_slice() {
        [] => {}
        [one] => {
            col_tests.entry(one.clone()).or_default().push(test(
                "unique",
                None,
                "primary-key",
                "the source's primary key",
            ));
        }
        many => {
            let mut a = Mapping::new();
            a.insert(
                "columns".into(),
                Value::Sequence(many.iter().map(|c| Value::from(ident(c))).collect()),
            );
            model_tests.push(test(
                "ekos_unique_combination",
                Some(Value::Mapping(a)),
                "primary-key",
                "the source's primary key",
            ));
        }
    }
    for m in &t.columns {
        let Some(f) = t.column_facts(&m.column) else {
            continue;
        };
        let mask = s.pii.get(&format!("{}.{}.{}", t.schema, t.table, m.column));
        // A null mask empties the column; an HMAC keeps one value per non-null input.
        if (f.not_null || t.primary_key.contains(&m.column)) && mask != Some(&MaskMethod::Null) {
            col_tests.entry(m.column.clone()).or_default().push(test(
                "not_null",
                None,
                "not-null",
                if f.not_null {
                    "the source column is NOT NULL"
                } else {
                    "a primary-key column"
                },
            ));
        }
        if !f.enum_labels.is_empty() && !masked(&m.column) {
            let mut a = Mapping::new();
            a.insert(
                "values".into(),
                Value::Sequence(
                    f.enum_labels
                        .iter()
                        .map(|l| Value::from(l.as_str()))
                        .collect(),
                ),
            );
            col_tests.entry(m.column.clone()).or_default().push(test(
                "accepted_values",
                Some(Value::Mapping(a)),
                "enum-labels",
                &format!("the labels of enum type {}", m.pg_type),
            ));
        }
        if let Some(class) = &f.pii_candidate
            && !masked(&m.column)
        {
            report
                .pii_candidates
                .push(format!("{}.{}.{} ({class})", t.schema, t.table, m.column));
        }
    }
    // One test per (column, target, target column): a source may declare the same key twice
    // (LedgerSMB does), and dbt refuses two tests with one name. The evidence names them all.
    let mut fk_names: BTreeMap<(String, String, String), Vec<String>> = BTreeMap::new();
    for fk in &t.facts.foreign_keys {
        if let ([c], [rc]) = (fk.columns.as_slice(), fk.ref_columns.as_slice()) {
            fk_names
                .entry((
                    c.clone(),
                    format!("{}.{}", fk.ref_schema, fk.ref_table),
                    rc.clone(),
                ))
                .or_default()
                .push(fk.name.clone());
        }
    }
    let mut tested: std::collections::BTreeSet<(String, String, String)> = Default::default();
    for fk in &t.facts.foreign_keys {
        let target = planned.get(&(fk.ref_schema.clone(), fk.ref_table.clone()));
        match (fk.columns.as_slice(), fk.ref_columns.as_slice(), target) {
            ([c], [rc], Some(target)) if !masked(c) => {
                let key = (
                    c.clone(),
                    format!("{}.{}", fk.ref_schema, fk.ref_table),
                    rc.clone(),
                );
                if !tested.insert(key.clone()) {
                    continue;
                }
                let mut a = Mapping::new();
                a.insert("to".into(), format!("ref('{}')", model_name(target)).into());
                a.insert(
                    "field".into(),
                    Value::from(if needs_quote(rc) {
                        ident(rc)
                    } else {
                        rc.clone()
                    }),
                );
                col_tests.entry(c.clone()).or_default().push(test(
                    "relationships",
                    Some(Value::Mapping(a)),
                    "foreign-key",
                    &format!("foreign key {}", fk_names[&key].join(", ")),
                ));
            }
            (_, _, None) => report.skipped_foreign_keys.push(format!(
                "{}.{} {}: {}.{} is not planned",
                t.schema, t.table, fk.name, fk.ref_schema, fk.ref_table
            )),
            ([_], _, _) => report.skipped_foreign_keys.push(format!(
                "{}.{} {}: the column is masked",
                t.schema, t.table, fk.name
            )),
            _ => report.skipped_foreign_keys.push(format!(
                "{}.{} {}: composite keys have no relationship test yet",
                t.schema, t.table, fk.name
            )),
        }
    }

    let mut columns = vec![];
    for m in &t.columns {
        let mut c = Mapping::new();
        c.insert("name".into(), m.column.clone().into());
        if needs_quote(&m.column) {
            c.insert("quote".into(), true.into());
        }
        if let Some(d) = t.column_facts(&m.column).and_then(|f| f.comment.clone()) {
            c.insert("description".into(), d.into());
        }
        c.insert("data_type".into(), m.iceberg_type.clone().into());
        if let Some(tests) = col_tests.remove(&m.column) {
            c.insert("data_tests".into(), Value::Sequence(tests));
        }
        columns.push(Value::Mapping(c));
    }
    let mut model = Mapping::new();
    model.insert("name".into(), model_name(t).into());
    if let Some(d) = &t.facts.comment {
        model.insert("description".into(), d.clone().into());
    }
    let mut ekos = Mapping::new();
    ekos.insert("source".into(), format!("{}.{}", t.schema, t.table).into());
    ekos.insert(
        "bronze".into(),
        format!("{}.{}", t.namespace, t.table).into(),
    );
    let mut meta = Mapping::new();
    meta.insert("ekos".into(), Value::Mapping(ekos));
    meta.insert("dagster".into(), dagster_meta(&model_name(t)));
    let mut cfg = Mapping::new();
    cfg.insert("meta".into(), Value::Mapping(meta));
    model.insert("config".into(), Value::Mapping(cfg));
    if !model_tests.is_empty() {
        model.insert("data_tests".into(), Value::Sequence(model_tests));
    }
    model.insert("columns".into(), Value::Sequence(columns));
    Value::Mapping(model)
}

/// The Dagster asset a silver node is: `silver/<name>`, in group `silver`.
fn dagster_meta(name: &str) -> Value {
    let mut d = Mapping::new();
    d.insert(
        "asset_key".into(),
        Value::Sequence(vec!["silver".into(), name.into()]),
    );
    d.insert("group".into(), "silver".into());
    Value::Mapping(d)
}

fn yaml(v: &Value) -> String {
    format!(
        "{YAML_HEADER}{}",
        serde_yaml::to_string(v).expect("YAML values serialize")
    )
}

fn sources_yaml(plan: &Plan) -> Value {
    let mut by_ns: BTreeMap<&str, Vec<&TablePlan>> = BTreeMap::new();
    for t in &plan.tables {
        by_ns.entry(t.namespace.as_str()).or_default().push(t);
    }
    let sources: Vec<Value> = by_ns
        .into_iter()
        .map(|(ns, tables)| {
            let tables: Vec<Value> = tables
                .iter()
                .map(|t| {
                    let mut dagster = Mapping::new();
                    dagster.insert(
                        "asset_key".into(),
                        Value::Sequence(vec!["bronze".into(), model_name(t).into()]),
                    );
                    let mut meta = Mapping::new();
                    meta.insert("dagster".into(), Value::Mapping(dagster));
                    let mut cfg = Mapping::new();
                    cfg.insert("meta".into(), Value::Mapping(meta));
                    let mut m = Mapping::new();
                    m.insert("name".into(), t.table.clone().into());
                    m.insert("config".into(), Value::Mapping(cfg));
                    Value::Mapping(m)
                })
                .collect();
            let mut src = Mapping::new();
            src.insert("name".into(), ns.into());
            src.insert(
                "database".into(),
                plan.settings.target_catalog.clone().into(),
            );
            src.insert("schema".into(), ns.into());
            src.insert("tables".into(), Value::Sequence(tables));
            Value::Mapping(src)
        })
        .collect();
    let mut root = Mapping::new();
    root.insert("version".into(), 2.into());
    root.insert("sources".into(), Value::Sequence(sources));
    Value::Mapping(root)
}

fn snapshot_yaml(t: &TablePlan) -> Value {
    let key: Value = match t.primary_key.as_slice() {
        [one] => one.clone().into(),
        many => Value::Sequence(many.iter().map(|k| Value::from(k.as_str())).collect()),
    };
    let mut cfg = Mapping::new();
    cfg.insert("schema".into(), silver_schema(t).into());
    cfg.insert("alias".into(), format!("{}_history", t.table).into());
    cfg.insert("unique_key".into(), key);
    match &t.decision.mode {
        LoadMode::Incremental { watermark, .. } => {
            cfg.insert("strategy".into(), "timestamp".into());
            cfg.insert("updated_at".into(), watermark.clone().into());
        }
        LoadMode::Full => {
            cfg.insert("strategy".into(), "check".into());
            cfg.insert("check_cols".into(), "all".into());
        }
    }
    let mut meta = Mapping::new();
    meta.insert(
        "dagster".into(),
        dagster_meta(&format!("{}_history", model_name(t))),
    );
    cfg.insert("meta".into(), Value::Mapping(meta));
    let mut snap = Mapping::new();
    snap.insert("name".into(), format!("{}_history", model_name(t)).into());
    snap.insert(
        "relation".into(),
        format!("ref('{}')", model_name(t)).into(),
    );
    snap.insert("config".into(), Value::Mapping(cfg));
    Value::Mapping(snap)
}

